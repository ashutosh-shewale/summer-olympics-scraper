"""Measure how long it takes to populate the database sequentially versus concurrently.

Only the "populate" phase is timed: draining a queue of already-discovered Games pages. Fetching
the index page happens once, before any timing, so every configuration does identical work.
"""

import os
import platform
import statistics
import time
from contextlib import closing
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from . import db
from .scrape import Mode, discover_games, prepare_queue, run_workers


@dataclass(frozen=True)
class Config:
    """One way of running the scraper."""

    mode: Mode
    workers: int

    @property
    def label(self) -> str:
        return "sequential" if self.mode == "sequential" else f"{self.workers} {self.mode}"


@dataclass(frozen=True)
class Result:
    """Timings for one configuration and its speed-up against the sequential baseline."""

    config: Config
    timings: list[float]
    median: float
    speedup_pct: float  # (t_sequential - t) / t_sequential, the time saved
    speedup_factor: float  # t_sequential / t


def run_benchmark(db_path: Path, thread_counts: list[int], process_counts: list[int], repeats: int) -> tuple[list[Result], int]:
    """Time every configuration ``repeats`` times; return results and the number of pages per run."""
    links = discover_games()
    prepare_queue(db_path, links)
    configs = [Config("sequential", 1)]
    configs += [Config("threads", n) for n in thread_counts]
    configs += [Config("processes", n) for n in process_counts]

    timings: dict[Config, list[float]] = {config: [] for config in configs}
    # Round-robin over configurations: if Wikipedia or the network slows down mid-benchmark,
    # every configuration is affected alike, instead of only whichever ran last.
    for round_number in range(1, repeats + 1):
        for config in configs:
            elapsed = _time_one_run(db_path, config, len(links))
            timings[config].append(elapsed)
            print(f"round {round_number}/{repeats}  {config.label:<14} {elapsed:6.2f}s", flush=True)

    baseline = statistics.median(timings[configs[0]])
    results = [_summarise(config, runs, baseline) for config, runs in timings.items()]
    return results, len(links)


def _time_one_run(db_path: Path, config: Config, expected_pages: int) -> float:
    """Reset the queue, drain it with ``config`` and return the wall-clock time taken."""
    with closing(db.connect(db_path)) as conn:
        db.requeue_all(conn)
    start = time.perf_counter()
    run_workers(db_path, config.mode, config.workers)
    elapsed = time.perf_counter() - start
    _ensure_complete(db_path, expected_pages, config)
    return elapsed


def _ensure_complete(db_path: Path, expected_pages: int, config: Config) -> None:
    """A run that skipped or failed pages did less work, so its time would not be comparable."""
    with closing(db.connect(db_path)) as conn:
        counts = db.status_counts(conn)
    if counts.get("done", 0) != expected_pages:
        raise RuntimeError(f"{config.label} run incomplete: {counts}")


def _summarise(config: Config, runs: list[float], baseline: float) -> Result:
    """Reduce raw timings to the median and the speed-up it represents."""
    median = statistics.median(runs)
    return Result(
        config=config,
        timings=runs,
        median=median,
        speedup_pct=100.0 * (baseline - median) / baseline,
        speedup_factor=baseline / median,
    )


def write_report(results: list[Result], pages: int, repeats: int, path: Path) -> None:
    """Write the results and the experimental set-up as a Markdown document."""
    rows = "\n".join(
        f"| {r.config.label} | {r.median:.2f} | {r.speedup_factor:.2f}× | {r.speedup_pct:+.1f}% | "
        + ", ".join(f"{t:.2f}" for t in r.timings)
        + " |"
        for r in results
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"""# Benchmark: populating the database

Generated by `python -m olympics benchmark` on {date.today().isoformat()}.

## Set-up

- **Workload:** scrape and parse {pages} Summer Olympics Wikipedia pages (1968–2020) and write them to SQLite.
  The index page is fetched once beforehand and is not timed.
- **Repeats:** {repeats} runs per configuration, interleaved round-robin; the table reports the median.
- **Speed-up:** `(t_sequential - t) / t_sequential`, i.e. the share of wall-clock time saved.
- **Machine:** {platform.platform()}, {os.cpu_count()} logical CPUs, Python {platform.python_version()}.
- **Network:** live requests to en.wikipedia.org over the benchmarking machine's connection; absolute times vary with the network,
  so compare configurations within one report, not across reports.

## Results

| Configuration | Median (s) | Speed-up | Time saved | All runs (s) |
|---|---|---|---|---|
{rows}
""",
        encoding="utf-8",
    )
